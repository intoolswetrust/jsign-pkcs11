package com.github.kwart.jsign.pkcs11;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.PrivateKey;
import java.security.Provider;
import java.security.Security;
import java.security.cert.Certificate;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.junit.jupiter.api.Assumptions;

/**
 * SoftHSM2 token shared by the tests of one JVM run.
 * <p>
 * The token is initialized with {@code softhsm2-util}, keys and self-signed certificates are generated by
 * {@code keytool} into a PKCS#12 file and imported into the token through the JSignPKCS11 KeyStore. The private
 * keys are imported as sensitive and not extractable, like on smart cards; the {@code *-always-auth} ones also with
 * {@code CKA_ALWAYS_AUTHENTICATE=true}.
 * <p>
 * Surefire sets {@code SOFTHSM2_CONF}. When SoftHSM2 is not installed, the tests are skipped unless the
 * {@code softhsm.required} system property is {@code true} (CI).
 */
final class SoftHsm {

    static final char[] PIN = "1234".toCharArray();
    static final String SO_PIN = "4321";
    static final String TOKEN_LABEL = "jsign";
    static final char[] P12_PASSWORD = "changeit".toCharArray();

    static final String RSA = "rsa";
    static final String EC256 = "ec256";
    static final String EC384 = "ec384";
    static final String RSA_ALWAYS_AUTH = "rsa-always-auth";
    static final String EC_ALWAYS_AUTH = "ec256-always-auth";

    /**
     * Hides the hash-and-sign mechanisms, so the provider hashes in Java and signs with raw CKM_RSA_PKCS/CKM_ECDSA.
     */
    static final String DISABLE_COMBINED_MECHANISMS = """
            disabledMechanisms = {
              CKM_SHA1_RSA_PKCS
              CKM_SHA224_RSA_PKCS
              CKM_SHA256_RSA_PKCS
              CKM_SHA384_RSA_PKCS
              CKM_SHA512_RSA_PKCS
              CKM_ECDSA_SHA1
              CKM_ECDSA_SHA224
              CKM_ECDSA_SHA256
              CKM_ECDSA_SHA384
              CKM_ECDSA_SHA512
            }
            """;

    private static final String SENSITIVE_IMPORT = """
            attributes(import, CKO_PRIVATE_KEY, *) = {
              CKA_SENSITIVE = true
              CKA_EXTRACTABLE = false
            %s}
            """;

    private static final List<String> LIBRARY_LOCATIONS = List.of(
            "/usr/lib/softhsm/libsofthsm2.so",
            "/usr/lib/x86_64-linux-gnu/softhsm/libsofthsm2.so",
            "/usr/lib/aarch64-linux-gnu/softhsm/libsofthsm2.so",
            "/usr/lib64/pkcs11/libsofthsm2.so",
            "/usr/local/lib/softhsm/libsofthsm2.so",
            "/opt/homebrew/lib/softhsm/libsofthsm2.so");

    private static SoftHsm instance;

    final String library;
    final long slot;
    final KeyStore softwareKeys;

    private int providerCounter;

    private SoftHsm(String library, Path dir) throws Exception {
        this.library = library;
        Path tokens = dir.resolve("tokens");
        if (Files.exists(tokens)) {
            try (Stream<Path> files = Files.walk(tokens)) {
                files.sorted(Comparator.reverseOrder()).forEach(p -> p.toFile().delete());
            }
        }
        Files.createDirectories(tokens);
        Files.writeString(dir.resolve("softhsm2.conf"),
                "directories.tokendir = " + tokens + "\nobjectstore.backend = file\nlog.level = INFO\n");

        String out = run(List.of("softhsm2-util", "--init-token", "--free", "--label", TOKEN_LABEL, "--pin",
                new String(PIN), "--so-pin", SO_PIN));
        Matcher m = Pattern.compile("reassigned to slot (\\d+)").matcher(out);
        if (!m.find()) {
            throw new IllegalStateException("Unexpected softhsm2-util output: " + out);
        }
        slot = Long.parseLong(m.group(1));

        Path p12 = dir.resolve("keys.p12");
        Files.deleteIfExists(p12);
        genKeyPair(p12, RSA, "-keyalg", "RSA", "-keysize", "2048");
        genKeyPair(p12, RSA_ALWAYS_AUTH, "-keyalg", "RSA", "-keysize", "2048");
        genKeyPair(p12, EC256, "-keyalg", "EC", "-groupname", "secp256r1");
        genKeyPair(p12, EC_ALWAYS_AUTH, "-keyalg", "EC", "-groupname", "secp256r1");
        genKeyPair(p12, EC384, "-keyalg", "EC", "-groupname", "secp384r1");
        softwareKeys = KeyStore.getInstance("PKCS12");
        try (InputStream is = Files.newInputStream(p12)) {
            softwareKeys.load(is, P12_PASSWORD);
        }

        importKeys("import", "", RSA, EC256, EC384);
        importKeys("import-always-auth", "  CKA_ALWAYS_AUTHENTICATE = true\n", RSA_ALWAYS_AUTH, EC_ALWAYS_AUTH);
    }

    static synchronized SoftHsm get() {
        if (instance == null) {
            String conf = System.getenv("SOFTHSM2_CONF");
            String library = System.getenv("SOFTHSM2_LIB");
            if (library == null) {
                library = LIBRARY_LOCATIONS.stream().filter(l -> Files.isRegularFile(Path.of(l))).findFirst()
                        .orElse(null);
            }
            if (conf == null || library == null || !isOnPath("softhsm2-util")) {
                String msg = "SoftHSM2 is not available (SOFTHSM2_CONF=" + conf + ", library=" + library
                        + "), run the tests with Maven on a system with SoftHSM2 installed";
                if (Boolean.getBoolean("softhsm.required")) {
                    throw new IllegalStateException(msg);
                }
                Assumptions.abort(msg);
            }
            try {
                instance = new SoftHsm(library, Path.of(conf).toAbsolutePath().getParent());
            } catch (Exception e) {
                throw new IllegalStateException("SoftHSM2 token setup failed", e);
            }
        }
        return instance;
    }

    String config(String name, String extra) {
        return "--name = " + name + "\nlibrary = " + library + "\nslot = " + slot + "\n" + extra;
    }

    /**
     * Returns a new provider instance; each has its own name, as the provider name is its identity.
     */
    synchronized JSignPKCS11 provider(String name, String extraConfig) {
        return new JSignPKCS11(config(name + "-" + (++providerCounter), extraConfig));
    }

    JSignPKCS11 combinedProvider() {
        return provider("combined", "");
    }

    JSignPKCS11 rawProvider() {
        return provider("raw", DISABLE_COMBINED_MECHANISMS);
    }

    static KeyStore keyStore(Provider provider) throws Exception {
        KeyStore ks = KeyStore.getInstance("JSIGNPKCS11", provider);
        ks.load(null, PIN);
        return ks;
    }

    /**
     * The JDK SunPKCS11 provider configured for the same token (used as a negative control).
     */
    Provider sunPkcs11() {
        return Security.getProvider("SunPKCS11").configure(config("sun-" + (++providerCounter), ""));
    }

    Certificate certificate(String alias) throws Exception {
        return softwareKeys.getCertificate(alias);
    }

    PrivateKey softwareKey(String alias) throws Exception {
        return (PrivateKey) softwareKeys.getKey(alias, P12_PASSWORD);
    }

    private void importKeys(String name, String extraAttributes, String... aliases) throws Exception {
        JSignPKCS11 importer = provider(name, SENSITIVE_IMPORT.formatted(extraAttributes));
        KeyStore ks = keyStore(importer);
        for (String alias : aliases) {
            ks.setKeyEntry(alias, softwareKey(alias), null, softwareKeys.getCertificateChain(alias));
        }
        KeyStore check = keyStore(importer);
        for (String alias : aliases) {
            if (!check.isKeyEntry(alias)) {
                throw new IllegalStateException("Key " + alias + " was not imported");
            }
        }
    }

    private static void genKeyPair(Path p12, String alias, String... keyArgs) throws Exception {
        List<String> cmd = new ArrayList<>(List.of(Path.of(System.getProperty("java.home"), "bin", "keytool").toString(),
                "-genkeypair", "-keystore", p12.toString(), "-storetype", "PKCS12", "-storepass",
                new String(P12_PASSWORD), "-alias", alias, "-dname", "CN=" + alias, "-validity", "365"));
        cmd.addAll(List.of(keyArgs));
        run(cmd);
    }

    private static boolean isOnPath(String command) {
        String path = System.getenv("PATH");
        return path != null && Stream.of(path.split(java.io.File.pathSeparator))
                .anyMatch(d -> Files.isExecutable(Path.of(d, command)));
    }

    private static String run(List<String> cmd) throws IOException, InterruptedException {
        Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
        String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        if (p.waitFor() != 0) {
            throw new IOException("Command " + cmd.get(0) + " failed: " + out);
        }
        return out;
    }
}
